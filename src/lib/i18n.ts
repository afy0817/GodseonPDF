const dicts: Record<Lang, Record<Key, string>> = { ko, en };

const isMac = /Mac/i.test(navigator.userAgent);
let lang: Lang = /^ko\b/i.test(navigator.language) ? 'ko' : 'en';
const listeners = new Set<(lang: Lang) => void>();

export function t(key: Key, params: Record<string, string | number> = {}): string {
  const all: Record<string, string | number> = { mod: isMac ? '⌘' : 'Ctrl', ...params };
  return dicts[lang][key].replace(/\{(\w+)\}/g, (m, k) => (k in all ? String(all[k]) : m));
}

export function getLang(): Lang {
  return lang;
}

export function setLang(next: Lang) {
  if (next !== 'ko' && next !== 'en') return;
  if (next === lang) return;
  lang = next;
  document.documentElement.lang = next;
  listeners.forEach((fn) => fn(next));
}

export function onLangChange(fn: (lang: Lang) => void) {
  listeners.add(fn);
}

/** data-i18n(글자), data-i18n-title, data-i18n-aria(aria-label) 속성이 있는 요소에 문구를 넣는다 */
export function applyI18n(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n as Key)));
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle as Key)));
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria as Key)));
}
